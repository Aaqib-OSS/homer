/**
 * comment-policy: a comment is a contract (KDoc, JSDoc, a docstring: at most 3 lines) or a constraint (at most 2),
 * cites only ADR, CWE, W and AR ids, and states every suppression's reason. Each rule and area has a ratcheted budget.
 * Usage (repository root): node tools/quality/comment-policy.mjs [out dir], or `--counts` to print today's counts.
 */
import fs from 'node:fs';
import path from 'node:path';
import { commentsOf, languageOf } from './comment-lexers.mjs';
import { listFiles } from './infra-lint.mjs';
import { codeText, runMain, writeCheck } from './lib.mjs';

export const BUDGET_FILE = 'tools/quality/comment-policy-budgets.json';
const TITLE = 'Comment policy: contracts and constraints only';
export const RULES = ['length', 'citation', 'shortcut-word', 'todo', 'narration', 'suppression-reason', 'suppression', 'remove-in'];
export const AREAS = ['backend-main', 'backend-test', 'console', 'python', 'infra', 'tools'];

/** Every path the check does not read, with its reason: captured or generated files, and kinds with no lexer. */
export const EXCLUDED = [
  { pattern: /(?:^|\/)node_modules\//, reason: 'installed dependencies' },
  { pattern: /(?:^|\/)(?:build|dist|\.next|coverage)\//, reason: 'build output' },
  { pattern: /^plugins\/homer-authoring\//, reason: 'generated copies of app/AGENT.md and the schemas' },
  { pattern: /^app\/app\/src\/test\/resources\/(?:claude|llm)\//, reason: 'captured CLI output streams' },
  { pattern: /(?:^|\/)gradle-wrapper\.properties$|(?:^|\/)gradlew(?:\.bat)?$/, reason: 'generated by `gradle wrapper`' },
  { pattern: /\.lock$|^tools\/pip-audit\/requirements\.txt$/, reason: 'generated dependency pins' },
  { pattern: /(?:^|\/)verification-(?:metadata\.xml|keyring\.keys)$/, reason: 'generated by Gradle dependency verification' },
  { pattern: /^(?:LICENSE|NOTICE)$/, reason: 'license texts' },
  { pattern: /\/META-INF\/services\//, reason: 'service registrations: class names only' },
  { pattern: /\.(?:md|html|xml|mmd|txt)$/, reason: 'Markdown, HTML, XML, Mermaid and text: no lexer; prose has its own checks' },
  { pattern: /\.jsonl?$/, reason: 'JSON: no comment syntax' },
  { pattern: /\.(?:png|svg|gif|ico|jpe?g|webp|jar|sqlite)$/, reason: 'binary or image' },
  { pattern: /^app\/e2e\/fixtures\/agents\/file-links\/(?:inside|outside)-link$/, reason: 'e2e fixture symlinks' },
];

/** Whether the check reads `file`: a language it lexes, outside `EXCLUDED`; its budgets and CHANGELOG.md change its result too. */
export const scanned = (file) => languageOf(file) !== null && !EXCLUDED.some(({ pattern }) => pattern.test(file));
export const reads = (file) => scanned(file) || file === BUDGET_FILE || file === 'CHANGELOG.md';

const INFRA = /^\.github\/|(?:^|\/)(?:Dockerfile(?:\.[^/]+)?|[^/]+\.Dockerfile|docker-compose[^/]*\.ya?ml)$/;

/** The budget area of a repository path. */
export function areaOf(file) {
  if (INFRA.test(file)) return 'infra';
  if (/^app\/(?:buildSrc\/|[^/]+\/src\/main\/)/.test(file)) return 'backend-main';
  if (/^app\/(?:[^/]+\/src\/test|e2e|architecture)\//.test(file)) return 'backend-test';
  if (file.startsWith('app/')) return /\.(?:sh|bash)$/.test(file) ? 'infra' : 'backend-main';
  if (/^(?:console|example)\//.test(file)) return 'console';
  if (file.startsWith('clients/python/')) return 'python';
  if (/^(?:tools|site)\//.test(file)) return 'tools';
  return 'infra';
}

/** 1-based line of an offset, by a binary search over the line starts. */
function lineIndex(text) {
  const starts = [0];
  for (let i = 0; i < text.length; i++) if (text[i] === '\n') starts.push(i + 1);
  return (offset) => {
    let [low, high] = [0, starts.length - 1];
    while (low < high) {
      const mid = (low + high + 1) >> 1;
      if (starts[mid] <= offset) low = mid;
      else high = mid - 1;
    }
    return low + 1;
  };
}

/**
 * The comment blocks of a source: a run of comment-only line comments on consecutive lines, or one block
 * comment, KDoc, JSDoc or docstring. `lines` holds the content lines, delimiters and blank lines left out.
 */
export function blocksOf(source, comments, language) {
  const lineAt = lineIndex(source);
  const blocks = [];
  for (const comment of comments) {
    const line = lineAt(comment.start);
    const ownLine = /^[ \t]*$/.test(source.slice(source.lastIndexOf('\n', comment.start - 1) + 1, comment.start));
    const starred = comment.kind !== 'line' && language !== 'python';
    const body = source.slice(comment.bodyStart, comment.bodyEnd).split('\n');
    const first = lineAt(comment.bodyStart);
    const lines = body
      .map((text, k) => ({ line: first + k, text: (starred ? text.trim().replace(/^\*/, '') : text).trim() }))
      .filter((l) => l.text !== '');
    const endLine = lineAt(Math.max(comment.start, comment.end - 1));
    const previous = blocks.at(-1);
    if (comment.kind === 'line' && ownLine && previous?.kind === 'line' && previous.ownLine && previous.endLine === line - 1) {
      previous.lines.push(...lines);
      previous.comments.push(comment);
      previous.endLine = endLine;
    } else {
      blocks.push({ kind: comment.kind, contract: comment.kind === 'doc', ownLine, line, endLine, lines, comments: [comment] });
    }
  }
  return blocks;
}

// Upper-case prefixes of `<KEY>-<n>` tokens that name a standard or an allowed citation, not an issue.
const NOT_ISSUE_KEYS = new Set(['ADR', 'CWE', 'AR', 'UTF', 'UTC', 'SHA', 'ISO', 'RFC', 'AES', 'HTTP', 'TLS', 'PKCS', 'GPL', 'LGPL', 'AGPL']);
const CITATIONS = [
  ['a URL', /\b(?:https?|ftp|file):\/\/[^\s`'"<>()[\]]+|\bwww\.[\w-]+\.[^\s`'"<>()[\]]+/gi],
  ['an issue number', /(?<![\w&#])#\d+\b/g],
  ['an issue key', /\b([A-Z][A-Z0-9]*[A-Z])-\d+(?:-\d+)?\b/g],
  ['a review-round reference', /\bfix-round\b|\breview round\b/gi],
];
const SHORTCUT =
  /\b(?:hack|workaround|work around|temporary|temporarily|for now|for the time being|until\b[^.]{0,60}\b(?:lands?|ships?|is fixed|are fixed|fixed|released|merged|upgraded?|supports?|carries|available)|stopgap|legacy|transitional|compat|compatibility|deprecated|best-effort|best effort|accepted risk|accepted residual|ideally|not ideal|simpler than|quick fix|kludge|deviat(?:e|es|ion|ing))\b/gi;
const SHORTCUT_CITATION = /\b(?:ADR-\d{4}|W-\d{3}|AR-\d{2}|removeIn\s+\d+\.\d+\.\d+)\b/;
const TODO = /\b(?:TODO|FIXME|XXX)\b/g;
const NARRATION = /previous implementation|audit\s*#|audit p\d+ #|\bpreviously\b|\bused to (?:be|hold|read|carry|have)\b/g;
const REMOVE_IN = /@?\bremoveIn\s+(\d+\.\d+\.\d+)\b/g;

const occurrence = (rule, line, message) => ({ rule, line, message });

function citationsOf({ line, text }) {
  return CITATIONS.flatMap(([what, pattern]) =>
    [...text.matchAll(pattern)]
      .filter((m) => what !== 'an issue key' || !NOT_ISSUE_KEYS.has(m[1]))
      .map((m) => occurrence('citation', line, `comment cites ${what} (${m[0]}): cite only ADR-NNNN, CWE-NNN, W-NNN or AR-NN`)),
  );
}

/** `[x, y, z]` of a version string. */
const parts = (version) => version.split('.').map(Number);
const atLeast = (version, wanted) => {
  const [a, b] = [parts(version), parts(wanted)];
  const at = a.findIndex((n, k) => n !== b[k]);
  return at < 0 || a[at] > b[at];
};

function removeInOccurrence(line, wanted, version) {
  if (!atLeast(version, wanted)) return [];
  return [occurrence('remove-in', line, `removeIn ${wanted}: the project is at ${version} (CHANGELOG.md), so remove what this marks`)];
}

/** Occurrences of the comment rules in one block; `version` is the project's released version. */
export function blockOccurrences(block, version) {
  const limit = block.contract ? 3 : 2;
  const found = [];
  // A suppression directive is a tool's annotation, not prose: its line does not count.
  const prose = block.lines.filter((l) => directiveOf(l.text, true) === null).length;
  if (prose > limit) {
    const what = block.contract ? 'contract comment' : 'comment';
    found.push(occurrence('length', block.line, `${what} of ${prose} lines (limit ${limit}): move the why into an ADR`));
  }
  const cited = SHORTCUT_CITATION.test(block.lines.map((l) => l.text).join('\n'));
  for (const l of block.lines) {
    found.push(...citationsOf(l));
    if (!cited) for (const m of l.text.matchAll(SHORTCUT)) found.push(occurrence('shortcut-word', l.line, `"${m[0]}" in a comment that cites no ADR-NNNN, W-NNN, AR-NN or removeIn x.y.z`));
    for (const m of l.text.matchAll(TODO)) found.push(occurrence('todo', l.line, `${m[0]} in a comment: fix it or file an issue`));
    for (const m of l.text.toLowerCase().matchAll(NARRATION)) found.push(occurrence('narration', l.line, `comment narrates what is gone ("${m[0]}")`));
    for (const m of l.text.matchAll(REMOVE_IN)) found.push(...removeInOccurrence(l.line, m[1], version));
  }
  return found;
}

/** A reason has real words: at least 3 non-space characters once markers are dropped, and not a bare to-do marker. */
export function isReasonText(raw) {
  const text = raw.trim().replace(/\}$/, '').trim().replace(/\*\/$/, '').replace(/^[\s#:*–—-]+/, '').trim();
  return text.replace(/\s/g, '').length >= 3 && !/^(todo|fixme)\W*$/i.test(text);
}

const DIRECTIVES = [
  { name: 'eslint-disable', pattern: /eslint-disable(?:-next-line|-line)?\b/, eslint: true },
  { name: '@ts-expect-error', pattern: /@ts-expect-error\b/ },
  { name: '@ts-ignore', pattern: /@ts-ignore\b/ },
  { name: 'noqa', pattern: /noqa\b(?::\s*[A-Z]+\d+(?:[\s,]+[A-Z]+\d+)*)?/i },
  { name: 'type: ignore', pattern: /type:\s*ignore\b(?:\[[^\]]*\])?/ },
  { name: 'shellcheck disable', pattern: /shellcheck\s+disable=[\w,-]+/ },
  { name: 'hadolint ignore', pattern: /hadolint\s+ignore=[\w,-]+/ },
  { name: 'zizmor: ignore', pattern: /zizmor:\s*ignore\b(?:\[[^\]]*\])?/ },
];

/** The suppression directive a comment body holds, at its start or (in a `#` comment) after another `#`: `{ name, reason }`. */
export function directiveOf(body, hash) {
  for (const { name, pattern, eslint } of DIRECTIVES) {
    const anchored = new RegExp(`${hash ? '(?:^|#)' : '^'}[\\s*]*(${pattern.source})`, pattern.flags);
    const m = anchored.exec(body);
    if (!m) continue;
    const rest = body.slice(m.index + m[0].length);
    const reason = eslint ? (rest.split(/\s--+\s/)[1] ?? '') : `${body.slice(0, m.index)} ${rest}`.replaceAll('#', ' ');
    return { name, reasoned: isReasonText(reason) };
  }
  return null;
}

const SUPPRESS = /@(?:file:)?Suppress\(/g;

// Each Kotlin `@Suppress(`: its line, and the line of the parenthesis closing it, read where strings and comments are blanked.
function suppressAnnotations(code) {
  const lineAt = lineIndex(code);
  return [...code.matchAll(SUPPRESS)].map((m) => {
    let [depth, j] = [0, m.index + m[0].length - 1];
    for (; j < code.length; j++) {
      if (code[j] === '(') depth++;
      else if (code[j] === ')' && --depth === 0) break;
    }
    return { line: lineAt(m.index), endLine: lineAt(Math.min(j, code.length - 1)) };
  });
}

function suppressionOccurrences(source, comments, language) {
  const lineAt = lineIndex(source);
  const lines = source.split('\n');
  const text = (line) => lines[line - 1].trim().slice(0, 120);
  const marked = comments.map((c) => {
    const body = source.slice(c.bodyStart, c.bodyEnd);
    const ownLine = /^[ \t]*$/.test(source.slice(source.lastIndexOf('\n', c.start - 1) + 1, c.start));
    return { line: lineAt(c.start), body, directive: directiveOf(body, source[c.start] === '#'), ownLine, kind: c.kind };
  });
  const above = new Map(marked.filter((c) => c.kind === 'line' && c.ownLine && !c.directive).map((c) => [c.line, c.body]));
  const reasonAbove = (line) => above.has(line - 1) && isReasonText(above.get(line - 1));
  const found = [];
  const add = (name, line, reasoned) => {
    found.push(occurrence('suppression', line, `${name}: ${text(line)}`));
    if (!reasoned) found.push(occurrence('suppression-reason', line, `${name} without a reason on its line or in a comment line directly above: ${text(line)}`));
  };
  for (const c of marked) if (c.directive) add(c.directive.name, c.line, c.directive.reasoned || reasonAbove(c.line));
  if (language !== 'kotlin') return found;
  const code = codeText(source);
  for (const a of suppressAnnotations(code)) {
    const inside = marked.some((c) => !c.directive && c.line >= a.line && c.line <= a.endLine && isReasonText(c.body));
    add('@Suppress', a.line, inside || reasonAbove(a.line));
  }
  return found;
}

/** Every rule occurrence in one file: `{ rule, area, path, line, message }`. */
export function scanFile(file, source, version) {
  const language = languageOf(file);
  const comments = commentsOf(language, source);
  const fromBlocks = blocksOf(source, comments, language).flatMap((b) => blockOccurrences(b, version));
  const suppressions = suppressionOccurrences(source, comments, language);
  const area = areaOf(file);
  return [...fromBlocks, ...suppressions].map((o) => ({ ...o, area, path: file }));
}

/** The newest released version in CHANGELOG.md: its first `## [x.y.z]` heading. */
export function projectVersion(changelog) {
  const version = /^## \[(\d+\.\d+\.\d+)\]/m.exec(changelog)?.[1];
  if (!version) throw new Error('comment-policy: CHANGELOG.md has no released `## [x.y.z]` heading');
  return version;
}

/** Occurrences per rule and area, every pair present: the budget file's shape. */
export function countsOf(occurrences) {
  const counts = Object.fromEntries(RULES.map((rule) => [rule, Object.fromEntries(AREAS.map((area) => [area, 0]))]));
  for (const o of occurrences) counts[o.rule][o.area]++;
  return counts;
}

/** The budgets of `text`; a missing, negative or unknown rule or area is an error, `$`-keys are notes. */
export function parseBudgets(text) {
  const budgets = JSON.parse(text);
  const unknown = Object.keys(budgets).filter((rule) => !rule.startsWith('$') && !RULES.includes(rule));
  if (unknown.length > 0) throw new Error(`${BUDGET_FILE}: unknown rule ${unknown.join(', ')}`);
  for (const rule of RULES) {
    for (const area of [...AREAS, ...Object.keys(budgets[rule] ?? {})]) {
      const budget = budgets[rule]?.[area];
      if (!AREAS.includes(area) || !Number.isInteger(budget) || budget < 0) throw new Error(`${BUDGET_FILE}: ${rule}.${area} must be a known area with a budget of 0 or more`);
    }
  }
  return budgets;
}

/** Slack a budget may sit above the count: 5% of the budget, rounded up, at least 1 (the size caps' rule, ADR-0082). */
export const slack = (budget) => Math.max(1, Math.ceil(budget / 20));
export const staleBudget = (budget, count) => (budget - count > slack(budget) ? count : null);

function budgetLine(text, rule, area) {
  const at = text.indexOf(`"${area}"`, Math.max(0, text.indexOf(`"${rule}"`)));
  return at < 0 ? 1 : text.slice(0, at).split('\n').length;
}

/** Findings of the budgets: every occurrence of a rule and area over its budget, and a budget left stale above its count. */
export function evaluate(occurrences, budgets, budgetText = '') {
  const groups = new Map();
  for (const o of occurrences) {
    const key = `${o.rule}|${o.area}`;
    groups.set(key, [...(groups.get(key) ?? []), o]);
  }
  const findings = [];
  for (const rule of RULES) {
    for (const area of AREAS) {
      const found = groups.get(`${rule}|${area}`) ?? [];
      const budget = budgets[rule][area];
      if (found.length > budget) {
        const over = `${area}: ${found.length} over the budget of ${budget} in ${BUDGET_FILE}`;
        findings.push(...found.map((o) => ({ path: o.path, line: o.line, severity: 'minor', message: `${rule}: ${o.message} (${over})`, stableKey: `${rule}: ${o.message}` })));
      }
      const lowerTo = staleBudget(budget, found.length);
      if (lowerTo !== null) {
        const message = `${rule}.${area}: the budget is ${budget} but the count is ${found.length}; lower it to ${lowerTo}`;
        findings.push({ path: BUDGET_FILE, line: budgetLine(budgetText, rule, area), severity: 'minor', message, stableKey: `${rule}.${area}: stale` });
      }
    }
  }
  return findings;
}

export function main(argv, { cwd = process.cwd(), files = undefined } = {}) {
  const read = (file) => fs.readFileSync(path.join(cwd, file), 'utf8');
  const list = (files ?? listFiles(cwd)).filter(scanned).sort();
  const version = projectVersion(read('CHANGELOG.md'));
  const occurrences = list.flatMap((file) => scanFile(file, read(file), version));
  const counts = countsOf(occurrences);
  if (argv[0] === '--counts') return `${JSON.stringify(counts, null, 2)}\n`;
  const budgetText = read(BUDGET_FILE);
  const findings = evaluate(occurrences, parseBudgets(budgetText), budgetText);
  const totals = Object.fromEntries(RULES.map((rule) => [rule, Object.values(counts[rule]).reduce((a, b) => a + b, 0)]));
  const outDir = argv[0] ?? 'reports/quality/comment-policy';
  const report = writeCheck(outDir, 'comment-policy', TITLE, findings, { files: list.length, ...totals });
  return report.split('\n').slice(0, 41).join('\n') + '\n';
}

runMain(import.meta, main);
